import type { BoundaryConfig, RequestConfig } from './config'
import type { EmitOptions, Emitted } from './emit'
import type { ResolutionContext } from './resolve-name'
import { posix } from 'node:path'
import { createMap } from '@hyperfrontend/immutable-api-utils/built-in-copy/map'
import { describe, expect, it } from '@hyperfrontend/testing'
import { emit } from './emit'
import { walk } from './walk'

const OPTIONS: EmitOptions = {
  header: { tool: 'tool', regenerate: 'regen', check: 'check' },
  boundary: { default: 'unknown', overrides: { Heavy: 'object' } },
  provenance: { repo: 'o/r', ref: 'v1', sha: 'abc', copyright: 'Copyright (c) Someone.' },
  index: 'out/index.ts',
  indexModule: 'pkg/compat',
}

const ROOT = { source: 'nx', root: 'src/root.ts', symbols: ['Root'], depth: 2, output: 'out/root.ts' }

/**
 * Walks and emits requests over in-memory files.
 *
 * @param files - Path to text, relative to the source `nx`
 * @param requests - The requests, defaulting to the one root
 * @param boundary - The boundary, defaulting to the shared one
 * @returns What was emitted
 */
function emitOver(files: Record<string, string>, requests: RequestConfig[] = [ROOT], boundary: BoundaryConfig = OPTIONS.boundary): Emitted {
  const context: ResolutionContext = {
    files: createMap(Object.entries(files).map(([path, text]) => [posix.join('nx', path), text])),
    include: ['nx/src/'],
    indexes: createMap(),
  }
  return emit(walk(requests, boundary, context), { ...OPTIONS, boundary })
}

/**
 * The body of an output: everything after the header and the imports.
 *
 * @param emitted - What was emitted
 * @param output - The output path
 * @returns The declarations' text
 */
function bodyOf(emitted: Emitted, output = 'out/root.ts'): string {
  const lines = (emitted.files.get(output) ?? '').split(/\r?\n/)
  const body = lines.slice(lines.indexOf(' */') + 1).filter((line) => !line.startsWith('import type '))
  while (body[0] === '') body.shift()
  return body.join('\n')
}

describe('emit', () => {
  it('writes a provenance header naming the commit, the upstream files, the roots and the depth', () => {
    const emitted = emitOver({ 'src/root.ts': 'export interface Root {}' })
    expect(emitted.files.get('out/root.ts')?.split(/\r?\n/).slice(0, 11)).toEqual([
      '/**',
      ' * Generated by tool from o/r at abc (v1). DO NOT EDIT.',
      ' *',
      ' * Declarations copied from:',
      ' *   src/root.ts',
      ' * Roots: Root',
      ' * Depth: 2; a reference past it, or outside the followed sources, is written as `unknown` and listed in REPORT.md.',
      ' * Regenerate with `regen`; verify with `check`.',
      ' *',
      ' * Copyright (c) Someone. Licensed under the terms reproduced in NOTICE.md.',
      ' */',
    ])
  })

  it('exports every declaration, keeping its JSDoc, and ends the file with one newline', () => {
    const emitted = emitOver({ 'src/root.ts': '/** The root. */\nexport interface Root { a: A }\n/** A. */\ninterface A {}\n' })
    expect(bodyOf(emitted)).toBe('/** The root. */\nexport interface Root { a: A }\n\n/** A. */\nexport interface A {}\n')
  })

  it('emits the roots first and the rest in the order they were reached', () => {
    const emitted = emitOver({ 'src/root.ts': 'export interface Root { z: Z; b: B }\ninterface Z {}\ninterface B {}' })
    expect(emitted.summaries[0]?.declarations).toEqual(['Root', 'Z', 'B'])
  })

  it('substitutes a reference past the depth and reports it', () => {
    const emitted = emitOver({
      'src/root.ts': 'export interface Root { a: A }\ninterface A { b: B }\ninterface B { c: C }\ninterface C {}',
    })
    expect({ body: bodyOf(emitted), entries: emitted.entries }).toEqual({
      body: 'export interface Root { a: A }\n\nexport interface A { b: B }\n\nexport interface B { c: unknown }\n',
      entries: [
        { output: 'out/root.ts', declaration: 'B', reference: 'C', position: 'property', reason: 'beyond-depth', replacement: 'unknown' },
      ],
    })
  })

  it('writes an override in place of the declaration it names and never emits it', () => {
    const emitted = emitOver({ 'src/root.ts': 'export interface Root { h: Heavy<string> }\ninterface Heavy<T> { t: T }' })
    expect({ body: bodyOf(emitted), entries: emitted.entries }).toEqual({
      body: 'export interface Root { h: object }\n',
      entries: [
        { output: 'out/root.ts', declaration: 'Root', reference: 'Heavy', position: 'property', reason: 'override', replacement: 'object' },
      ],
    })
  })

  it('covers an indexed access, a parenthesised type, keyof and Pick built on a substituted type', () => {
    const files = {
      'src/root.ts':
        "export interface Root { a: Heavy['x']; b: (typeof v)[number]; c: keyof Heavy; d: Pick<Heavy, 'x'>; e: Omit<Heavy, 'x'> }\ninterface Heavy { x: 1 }",
    }
    expect(bodyOf(emitOver(files))).toBe('export interface Root { a: unknown; b: unknown; c: unknown; d: unknown; e: unknown }\n')
  })

  it('drops a substituted type from a heritage clause and removes an emptied clause', () => {
    const files = { 'src/root.ts': "import { Ext } from 'pkg'\nexport interface Root extends Ext, Base {}\ninterface Base extends Ext {}" }
    expect({ body: bodyOf(emitOver(files)), entries: emitOver(files).entries.map((entry) => entry.replacement) }).toEqual({
      body: 'export interface Root extends Base {}\n\nexport interface Base {}\n',
      entries: ['dropped from the heritage clause', 'dropped from the heritage clause'],
    })
  })

  it('rewrites any, typeof, import types and untyped parameters and members', () => {
    const files = {
      'src/root.ts': 'export interface Root { a: any; t: typeof v; i: import("./m").T; f: (x, ...r) => void; p; m(y: number) }',
    }
    expect(bodyOf(emitOver(files))).toBe(
      'export interface Root { a: unknown; t: unknown; i: unknown; f: (x: unknown, ...r: unknown[]) => void; p: unknown; m(y: number): unknown }\n'
    )
  })

  it('reports each rewrite with its kind', () => {
    const files = { 'src/root.ts': 'export interface Root { a: any; f: (x) => void; p }' }
    expect(emitOver(files).entries.map((entry) => [entry.reference, entry.reason, entry.replacement])).toEqual([
      ['any', 'any', 'unknown'],
      ['x', 'untyped-parameter', 'annotated with unknown'],
      ['p', 'untyped-member', 'annotated with unknown'],
    ])
  })

  it('imports Node built-in types and renames a namespace access to the imported name', () => {
    const files = {
      'src/root.ts': "import type { Mode as M } from 'node:fs'\nimport * as fs from 'fs'\nexport interface Root { a: M; b: fs.Stats }",
    }
    const text = emitOver(files).files.get('out/root.ts') ?? ''
    expect(text).toContain("import type { Mode as M, Stats } from 'node:fs'\n\nexport interface Root { a: M; b: Stats }")
  })

  it('imports a declaration placed in another output and writes the barrel', () => {
    const files = { 'src/root.ts': 'export interface Root { o: Other }\nexport interface Other { r: Root }' }
    const emitted = emitOver(files, [ROOT, { ...ROOT, symbols: ['Other'], depth: 0, output: 'out/nested/other.ts' }])
    expect({
      root: emitted.files.get('out/root.ts')?.includes("import type { Other } from './nested/other'\n\nexport interface Root { o: Other }"),
      other: emitted.files
        .get('out/nested/other.ts')
        ?.includes("import type { Root } from '../root'\n\nexport interface Other { r: Root }"),
      index: emitted.files.get('out/index.ts'),
    }).toEqual({
      root: true,
      other: true,
      index: [
        '/**',
        ' * Upstream-compatible declarations of o/r at abc (v1), generated by',
        ' * tool; every name is re-exported here. DO NOT EDIT.',
        ' * Regenerate with `regen`; verify with `check`.',
        ' *',
        ' * @module pkg/compat',
        ' */',
        "export type { Other } from './nested/other'",
        "export type { Root } from './root'",
        '',
      ].join('\n'),
    })
  })

  it('imports a sibling declaration once however often it is referenced', () => {
    const files = { 'src/root.ts': 'export interface Root { a: Other; b: Other }\nexport interface Other {}' }
    const emitted = emitOver(files, [ROOT, { ...ROOT, symbols: ['Other'], depth: 0, output: 'out/other.ts' }])
    expect(emitted.files.get('out/root.ts')).toContain(
      "import type { Other } from './other'\n\nexport interface Root { a: Other; b: Other }"
    )
  })

  it('imports two declarations from one sibling output in one statement', () => {
    const files = { 'src/root.ts': 'export interface Root { a: Other; b: Third }\nexport interface Other {}\nexport interface Third {}' }
    const emitted = emitOver(files, [ROOT, { ...ROOT, symbols: ['Other', 'Third'], depth: 0, output: 'out/other.ts' }])
    expect(emitted.files.get('out/root.ts')).toContain(
      "import type { Other, Third } from './other'\n\nexport interface Root { a: Other; b: Third }"
    )
  })

  it('imports a built-in name once however often it is used', () => {
    const files = { 'src/root.ts': "import * as fs from 'node:fs'\nexport interface Root { a: fs.Stats; b: fs.Stats }" }
    expect(emitOver(files).files.get('out/root.ts')).toContain(
      "import type { Stats } from 'node:fs'\n\nexport interface Root { a: Stats; b: Stats }"
    )
  })

  it('aliases a built-in import whose name a local declaration took', () => {
    const files = { 'src/root.ts': "import * as fs from 'node:fs'\nexport interface Root { a: fs.Stats; b: Stats }\ninterface Stats {}" }
    expect(emitOver(files).files.get('out/root.ts')).toContain(
      "import type { Stats as Stats_2 } from 'node:fs'\n\nexport interface Root { a: Stats_2; b: Stats }"
    )
  })

  it('writes a long re-export one name per line, as the formatter would', () => {
    const names = [
      'Alpha',
      'Bravo',
      'Charlie',
      'Delta',
      'Echo',
      'Foxtrot',
      'Golf',
      'Hotel',
      'India',
      'Juliet',
      'Kilo',
      'Lima',
      'Mike',
      'November',
    ]
    const declarations = names.map((name) => `export interface ${name}Configuration {}`).join('\n')
    const members = names.map((name) => `${name.toLowerCase()}: ${name}Configuration`).join('; ')
    const files = { 'src/root.ts': `export interface Root { ${members} }\n${declarations}` }
    const expected = [...names.map((name) => `${name}Configuration`), 'Root'].sort()
    expect(emitOver(files).files.get('out/index.ts')).toContain(
      `export type {\n${expected.map((name) => `  ${name},`).join('\n')}\n} from './root'\n`
    )
  })

  it('renames a colliding declaration and the references to it', () => {
    const files = {
      'src/root.ts': "import { A as Imported } from './a'\nexport interface Root { x: Imported; y: A }\ninterface A {}",
      'src/a.ts': 'export interface A {}',
    }
    const emitted = emitOver(files)
    expect({
      body: bodyOf(emitted),
      renames: emitted.entries.filter((entry) => entry.reason === 'renamed').map((entry) => entry.replacement),
    }).toEqual({
      body: 'export interface Root { x: A; y: A_2 }\n\nexport interface A {}\n\nexport interface A_2 {}\n',
      renames: ['A is carried as A_2'],
    })
  })

  it('aliases an imported declaration whose name a local one took', () => {
    const files = {
      'src/root.ts':
        'export interface Root { s: Shared; t: Twin }\ninterface Shared {}\nexport interface Twin { u: Shared2 }\ninterface Shared2 {}',
    }
    const requests = [ROOT, { ...ROOT, symbols: ['Twin'], depth: 1, output: 'out/twin.ts' }]
    const text = emitOver(files, requests).files.get('out/twin.ts') ?? ''
    expect(text).toContain('export interface Twin { u: Shared2 }')
  })

  it('flattens a namespace member under a prefixed name and dedents it', () => {
    const files = {
      'src/root.ts':
        'export interface Root { m: Space.Member }\nnamespace Space {\n  /** M. */\n  export interface Member {\n    x: 1\n  }\n}',
    }
    expect(bodyOf(emitOver(files))).toBe(
      'export interface Root { m: Space_Member }\n\n/** M. */\nexport interface Space_Member {\n  x: 1\n}\n'
    )
  })

  it('carries a class as an interface, a declare keyword removed and CRLF endings normalised', () => {
    const files = {
      'src/root.ts':
        'export interface Root { k: Klass; d: Declared }\r\nclass Klass { run(): void {} }\r\ndeclare interface Declared {\r\n  x: 1\r\n}',
    }
    expect(bodyOf(emitOver(files))).toBe(
      'export interface Root { k: Klass; d: Declared }\n\nexport interface Klass {\n    run(): void;\n}\n\nexport interface Declared {\n  x: 1\n}\n'
    )
  })

  it('writes enum members as literals and carries the enum as a union', () => {
    const files = {
      'src/root.ts': "export interface Root { k: Kind; s: Kind.Static }\nenum Kind { Static = 'static', Dynamic = 'dynamic' }",
    }
    expect(bodyOf(emitOver(files))).toBe("export interface Root { k: Kind; s: 'static' }\n\nexport type Kind = 'static' | 'dynamic';\n")
  })

  it('summarises each output with its roots, depth, declarations and upstream files', () => {
    const files = { 'src/root.ts': "import { A } from './a'\nexport interface Root { a: A }", 'src/a.ts': 'export interface A {}' }
    expect(emitOver(files).summaries).toEqual([
      { output: 'out/root.ts', roots: ['Root'], depth: 2, declarations: ['Root', 'A'], sourceFiles: ['nx/src/a.ts', 'nx/src/root.ts'] },
    ])
  })

  it('writes no import block when nothing is imported', () => {
    const text = emitOver({ 'src/root.ts': 'export interface Root {}' }).files.get('out/root.ts') ?? ''
    expect(text.endsWith(' */\n\nexport interface Root {}\n')).toBe(true)
  })

  it('keeps a global qualified name as written', () => {
    expect(bodyOf(emitOver({ 'src/root.ts': 'export interface Root { t: NodeJS.Timeout }' }))).toBe(
      'export interface Root { t: NodeJS.Timeout }\n'
    )
  })

  it('strips a trailing period from the copyright line before adding its own', () => {
    const context: ResolutionContext = {
      files: createMap([['nx/src/root.ts', 'export interface Root {}']]),
      include: ['nx/src/'],
      indexes: createMap(),
    }
    const emitted = emit(walk([ROOT], OPTIONS.boundary, context), {
      ...OPTIONS,
      provenance: { ...OPTIONS.provenance, copyright: 'Copyright (c) Nobody' },
    })
    expect(emitted.files.get('out/root.ts')).toContain(' * Copyright (c) Nobody. Licensed under')
  })
})
