import type { ReportContext } from './report'
import { describe, expect, it } from '@hyperfrontend/testing'
import { renderNotice, renderReport } from './report'

const CONTEXT: ReportContext = {
  header: { tool: 'tool', regenerate: 'regen', check: 'check' },
  provenance: { repo: 'o/r', ref: 'v1', sha: 'abc', copyright: 'Copyright (c) Someone.' },
  summaries: [
    { output: 'out/a.ts', roots: ['A'], depth: 2, declarations: ['A', 'B'], sourceFiles: ['nx/src/a.ts', 'nx/src/b.ts'] },
    { output: 'out/c.ts', roots: ['C'], depth: 1, declarations: ['C'], sourceFiles: ['nx/src/c.ts'] },
  ],
  entries: [
    { output: 'out/a.ts', declaration: 'B', reference: 'Z', position: 'property', reason: 'beyond-depth', replacement: 'unknown' },
    { output: 'out/a.ts', declaration: 'A', reference: 'x | y', position: 'alias', reason: 'typeof', replacement: 'unknown' },
    {
      output: 'out/a.ts',
      declaration: 'A',
      reference: '',
      position: '',
      reason: 'rewritten',
      replacement: 'an enum, carried as the union of its member values',
    },
  ],
}

describe('renderReport', () => {
  const report = renderReport(CONTEXT)

  it('opens with the provenance and the commands', () => {
    expect(report.split(/\r?\n/).slice(0, 3)).toEqual([
      '# Generated declarations: report',
      '',
      'Generated by tool from o/r at `abc` (v1). This file is generated with the declarations; regenerate with `regen` and verify with `check`.',
    ])
  })

  it('tabulates every output with its roots, depth, count and upstream files', () => {
    expect(report).toContain(
      '| Output | Roots | Depth | Declarations | Upstream files |\n| --- | --- | --- | --- | --- |\n| out/a.ts | A | 2 | 2 | src/a.ts, src/b.ts |\n| out/c.ts | C | 1 | 1 | src/c.ts |'
    )
  })

  it('escapes a backslash ahead of the pipe in a cell', () => {
    const entry: ReportContext['entries'][number] = {
      output: 'out/c.ts',
      declaration: 'C',
      reference: 'x \\| y',
      position: 'alias',
      reason: 'typeof',
      replacement: 'unknown',
    }
    expect(renderReport({ ...CONTEXT, entries: [entry] })).toContain('| C | x \\\\\\| y | alias | typeof | unknown |')
  })

  it('explains every reason in alphabetical order', () => {
    const legend = report.slice(report.indexOf('## Reasons'), report.indexOf('## out/a.ts'))
    expect(
      legend
        .split(/\r?\n/)
        .filter((line) => line.startsWith('| ') && !line.startsWith('| Reason') && !line.startsWith('| ---'))
        .map((line) => line.split(' | ')[0]?.slice(2))
    ).toEqual([
      'any',
      'beyond-depth',
      'enum-member',
      'external-module',
      'import-type',
      'namespace',
      'override',
      'qualified-name',
      'renamed',
      'rewritten',
      'typeof',
      'unresolved',
      'untyped-member',
      'untyped-parameter',
      'value-declaration',
    ])
  })

  it('sorts the rows of an output by declaration then reference and escapes pipes and empty cells', () => {
    expect(report.slice(report.indexOf('## out/a.ts'), report.indexOf('## out/c.ts'))).toBe(
      [
        '## out/a.ts',
        '',
        '| Declaration | Reference | Position | Reason | Written as |',
        '| --- | --- | --- | --- | --- |',
        '| A | - | - | rewritten | an enum, carried as the union of its member values |',
        '| A | x \\| y | alias | typeof | unknown |',
        '| B | Z | property | beyond-depth | unknown |',
        '',
        '',
      ].join('\n')
    )
  })

  it('says when an output carries everything as written', () => {
    expect(report.endsWith('## out/c.ts\n\nEvery reference is carried as written.\n')).toBe(true)
  })
})

describe('renderNotice', () => {
  it('lists the upstream files once, sorted, and reproduces the license', () => {
    expect(renderNotice(CONTEXT, 'MIT\r\n\r\nCopyright (c) Someone.\r\n')).toBe(
      [
        '# Third-party notice',
        '',
        'The TypeScript declarations in this directory were copied, and transformed as REPORT.md describes, from o/r at commit `abc` (v1) by tool. The upstream files read:',
        '',
        '- `src/a.ts`',
        '- `src/b.ts`',
        '- `src/c.ts`',
        '',
        'Their license follows verbatim.',
        '',
        '## Upstream license',
        '',
        'MIT',
        '',
        'Copyright (c) Someone.',
        '',
      ].join('\n')
    )
  })
})
