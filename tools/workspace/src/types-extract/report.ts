/**
 * The generated report of every substitution and rewrite, and the notice carrying the upstream
 * license and the files copied.
 *
 * @module types-extract/report
 */

import type { HeaderConfig } from './config'
import type { OutputSummary, Provenance, ReportEntry } from './emit'
import { keys } from '@hyperfrontend/immutable-api-utils/built-in-copy/object'
import { createSet } from '@hyperfrontend/immutable-api-utils/built-in-copy/set'
import { compareText } from './compare'
import { repositoryPath } from './sources'

/** What a report and a notice are rendered from. */
export interface ReportContext {
  /** The header's wording. */
  readonly header: HeaderConfig
  /** Where the declarations came from. */
  readonly provenance: Provenance
  /** One summary per output. */
  readonly summaries: readonly OutputSummary[]
  /** The report's rows. */
  readonly entries: readonly ReportEntry[]
}

/** What each reason means, for the report's legend. */
const REASONS: Readonly<Record<string, string>> = {
  'beyond-depth': 'the declaration lies deeper than the request follows',
  override: 'the configuration names the declaration as never carried',
  'external-module': 'the declaration lives in a package or outside the followed sources',
  unresolved: 'no followed module exports the name',
  'qualified-name': 'a dotted name the extraction does not follow',
  'value-declaration': 'the name is a function or variable, not a type',
  namespace: 'the name is a namespace used as a type',
  'enum-member': 'an enum member, written as its literal value',
  typeof: 'the type of a runtime value, which cannot be carried',
  'import-type': 'an inline import type',
  any: '`any`, written as `unknown`',
  'untyped-parameter': 'a parameter without a type, annotated',
  'untyped-member': 'a member without a type, annotated',
  renamed: 'the declaration is emitted under another name',
  rewritten: 'the declaration was changed as described',
}

/**
 * A table cell: backslashes and pipes escaped, empty shown as a dash.
 *
 * @param text - The raw text of the cell
 * @returns The text, safe inside a table row
 */
function cell(text: string): string {
  return text === '' ? '-' : text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

/**
 * The order of a report row: by declaration, reference, position, then reason.
 *
 * @param entry - The row
 * @returns A key that sorts as the row should
 */
function sortKey(entry: ReportEntry): string {
  return [entry.declaration, entry.reference, entry.position, entry.reason].join('\u0000')
}

/**
 * Renders the report.
 *
 * @param context - What to report on
 * @returns Markdown
 */
export function renderReport(context: ReportContext): string {
  const { header, provenance } = context
  const lines = [
    '# Generated declarations: report',
    '',
    `Generated by ${header.tool} from ${provenance.repo} at \`${provenance.sha}\` (${provenance.ref}). This file is generated with the declarations; regenerate with \`${header.regenerate}\` and verify with \`${header.check}\`.`,
    '',
    '## Outputs',
    '',
    '| Output | Roots | Depth | Declarations | Upstream files |',
    '| --- | --- | --- | --- | --- |',
    ...context.summaries.map(
      (summary) =>
        `| ${cell(summary.output)} | ${cell(summary.roots.join(', '))} | ${summary.depth} | ${summary.declarations.length} | ${cell(summary.sourceFiles.map(repositoryPath).join(', '))} |`
    ),
    '',
    '## Reasons',
    '',
    '| Reason | Meaning |',
    '| --- | --- |',
    ...keys(REASONS)
      .sort(compareText)
      .map((reason) => `| ${reason} | ${REASONS[reason]} |`),
  ]
  for (const summary of context.summaries) {
    const rows = context.entries.filter((entry) => entry.output === summary.output).sort((a, b) => compareText(sortKey(a), sortKey(b)))
    lines.push('', `## ${summary.output}`, '')
    if (rows.length === 0) {
      lines.push('Every reference is carried as written.')
      continue
    }
    lines.push('| Declaration | Reference | Position | Reason | Written as |', '| --- | --- | --- | --- | --- |')
    for (const row of rows) {
      lines.push(
        `| ${cell(row.declaration)} | ${cell(row.reference)} | ${cell(row.position)} | ${cell(row.reason)} | ${cell(row.replacement)} |`
      )
    }
  }
  return `${lines.join('\n')}\n`
}

/**
 * Renders the notice.
 *
 * @param context - What to report on
 * @param license - The upstream license text, verbatim
 * @returns Markdown
 */
export function renderNotice(context: ReportContext, license: string): string {
  const files = [...createSet(context.summaries.flatMap((summary) => summary.sourceFiles))].sort(compareText)
  const lines = [
    '# Third-party notice',
    '',
    `The TypeScript declarations in this directory were copied, and transformed as REPORT.md describes, from ${context.provenance.repo} at commit \`${context.provenance.sha}\` (${context.provenance.ref}) by ${context.header.tool}. The upstream files read:`,
    '',
    ...files.map((file) => `- \`${repositoryPath(file)}\``),
    '',
    'Their license follows verbatim.',
    '',
    '## Upstream license',
    '',
    ...license.replace(/\r\n/g, '\n').trimEnd().split(/\r?\n/),
  ]
  return `${lines.join('\n')}\n`
}
