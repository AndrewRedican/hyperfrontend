/** Props for the shared stroked-icon frame. */
interface OutlineProps extends IconProps {
  /** The paths that draw the mark */
  children: React.ReactNode
}

/**
 * The frame every stroked icon in this set shares, so they line up at any size.
 * @param props - Component props
 * @param props.className - Sizing and colour classes
 * @param props.children - The paths that draw the mark
 * @returns The rendered icon, hidden from assistive technology
 */
function Outline({ className = 'h-4 w-4', children }: OutlineProps) {
  return (
    <svg
      className={`${className} shrink-0`}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.5}
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  )
}
