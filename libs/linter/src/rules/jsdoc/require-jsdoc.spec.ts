/** Every context, with the rest of the workspace's options. */
const WORKSPACE: Options = { ...REST, checkSetters: 'no-getter', contexts: SELECTORS.map(([, name]) => name) }

/** The message reported. */
const MISSING = 'Missing JSDoc comment.'

/**
 * A case linted with the workspace's options.
 *
 * @param name - What it exercises
 * @param text - The code
 * @param options - The options, the workspace's unless given
 * @returns The case
 */
function valid(name: string, text: string, options: Options = WORKSPACE): RuleCase {
  return { name, path: '/root/file.ts', text, options }
}

